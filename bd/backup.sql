-- O backend define app.usuario_id usando set_config(..., true), dentro da transação.
-- 'true' = SET LOCAL: a identidade não vaza para outra requisição no PgBouncer.
CREATE OR REPLACE FUNCTION app.fn_usuario_atual()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY INVOKER AS $$
    SELECT NULLIF(current_setting('app.usuario_id', true), '')::BIGINT;
$$;

-- RLS na matrícula (isolamento do professor pelo docente responsável pela turma).
ALTER TABLE app.matriculas ENABLE ROW LEVEL SECURITY;
CREATE POLICY pol_matricula_acesso ON app.matriculas FOR ALL
    USING (
        current_user = 'usr_coordenador'
        OR EXISTS (
            SELECT 1 FROM app.turmas t
            WHERE t.id = turma_id AND t.professor_id = app.fn_usuario_atual()
        )
    )
    WITH CHECK (
        current_user = 'usr_coordenador'
        OR EXISTS (
            SELECT 1 FROM app.turmas t
            WHERE t.id = turma_id AND t.professor_id = app.fn_usuario_atual()
        )
    );

CREATE OR REPLACE FUNCTION app.fn_pode_acessar_matricula(p_matricula_id BIGINT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY INVOKER AS $$
    SELECT EXISTS (SELECT 1 FROM app.matriculas m WHERE m.id = p_matricula_id);
$$;

ALTER TABLE app.notas ENABLE ROW LEVEL SECURITY;
CREATE POLICY pol_notas_acesso ON app.notas FOR ALL
    USING (app.fn_pode_acessar_matricula(matricula_id))
    WITH CHECK (app.fn_pode_acessar_matricula(matricula_id));
ALTER TABLE app.frequencias ENABLE ROW LEVEL SECURITY;
CREATE POLICY pol_frequencias_acesso ON app.frequencias FOR ALL
    USING (app.fn_pode_acessar_matricula(matricula_id))
    WITH CHECK (app.fn_pode_acessar_matricula(matricula_id));

-- FUNCTION obrigatória: retorna média, percentual de frequência e situação.
CREATE OR REPLACE FUNCTION app.fn_situacao_aluno(p_matricula_id BIGINT)
RETURNS TABLE(media NUMERIC, percentual_frequencia NUMERIC, situacao TEXT)
LANGUAGE plpgsql STABLE SECURITY INVOKER AS $$
DECLARE
    v_media NUMERIC;
    v_frequencia NUMERIC;
    v_total BIGINT;
    v_presentes BIGINT;
    v_situacao TEXT;
BEGIN
    SELECT ROUND((n.nota1 + n.nota2) / 2, 2)
      INTO v_media FROM app.notas n WHERE n.matricula_id = p_matricula_id;
    SELECT COUNT(*), COUNT(*) FILTER (WHERE f.presente)
      INTO v_total, v_presentes FROM app.frequencias f WHERE f.matricula_id = p_matricula_id;
    v_frequencia := CASE WHEN v_total = 0 THEN 0
        ELSE ROUND(100.0 * v_presentes / v_total, 2) END;
    IF v_media IS NULL THEN
        v_situacao := 'SEM NOTAS';
    ELSIF v_total = 0 THEN
        v_situacao := 'SEM FREQUENCIA';
    ELSIF v_media >= 6 AND v_frequencia >= 75 THEN
        v_situacao := 'APROVADO';
    ELSE
        v_situacao := 'REPROVADO';
    END IF;
    RETURN QUERY SELECT v_media, v_frequencia, v_situacao;
END;
$$;

-- PROCEDURE obrigatória: lançamento ou atualização atômica, auditada por trigger.
-- COMMIT/ROLLBACK são controlados pela transação do Spring (necessário com SET LOCAL).
CREATE OR REPLACE PROCEDURE app.sp_lancar_notas(
    p_matricula_id BIGINT, p_nota1 NUMERIC, p_nota2 NUMERIC
) LANGUAGE plpgsql SECURITY INVOKER AS $$
BEGIN
    IF p_nota1 IS NULL OR p_nota2 IS NULL
       OR p_nota1 NOT BETWEEN 0 AND 10 OR p_nota2 NOT BETWEEN 0 AND 10 THEN
        RAISE EXCEPTION 'Notas devem estar entre 0 e 10';
    END IF;
    INSERT INTO app.notas(matricula_id, nota1, nota2)
    VALUES (p_matricula_id, p_nota1, p_nota2)
    ON CONFLICT (matricula_id) DO UPDATE SET
        nota1 = EXCLUDED.nota1,
        nota2 = EXCLUDED.nota2,
        atualizada_em = now();
END;
$$;

-- TRIGGER obrigatório: rastreia INSERT/UPDATE/DELETE de notas e frequências.
CREATE OR REPLACE FUNCTION audit.fn_auditar_alteracao()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, audit AS $$
DECLARE
    v_antes JSONB;
    v_depois JSONB;
    v_id BIGINT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_antes := NULL; v_depois := to_jsonb(NEW); v_id := NEW.id;
    ELSIF TG_OP = 'UPDATE' THEN
        v_antes := to_jsonb(OLD); v_depois := to_jsonb(NEW); v_id := NEW.id;
    ELSE
        v_antes := to_jsonb(OLD); v_depois := NULL; v_id := OLD.id;
    END IF;
    INSERT INTO audit.log_eventos(tabela, operacao, registro_id, usuario_id,
                                  role_db, dados_antes, dados_depois)
    VALUES (TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME, TG_OP, v_id,
            NULLIF(current_setting('app.usuario_id', true), '')::BIGINT,
            session_user, v_antes, v_depois);
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_auditar_notas
    AFTER INSERT OR UPDATE OR DELETE ON app.notas
    FOR EACH ROW EXECUTE FUNCTION audit.fn_auditar_alteracao();
CREATE TRIGGER trg_auditar_frequencias
    AFTER INSERT OR UPDATE OR DELETE ON app.frequencias
    FOR EACH ROW EXECUTE FUNCTION audit.fn_auditar_alteracao();

-- Views com SECURITY INVOKER: respeitam a RLS do usuário SQL chamador.
CREATE OR REPLACE VIEW app.vw_boletim WITH (security_invoker = true) AS
SELECT m.id AS matricula_id, a.id AS aluno_id, a.nome AS aluno,
       t.id AS turma_id, t.nome AS turma, d.nome AS disciplina,
       n.nota1, n.nota2, r.media, r.percentual_frequencia, r.situacao
FROM app.matriculas m
JOIN app.alunos a ON a.id = m.aluno_id
JOIN app.turmas t ON t.id = m.turma_id
JOIN app.disciplinas d ON d.id = t.disciplina_id
LEFT JOIN app.notas n ON n.matricula_id = m.id
CROSS JOIN LATERAL app.fn_situacao_aluno(m.id) r;

CREATE OR REPLACE VIEW app.vw_frequencia_resumo WITH (security_invoker = true) AS
SELECT m.id AS matricula_id, a.nome AS aluno, t.nome AS turma,
       COUNT(f.id) AS total_aulas,
       COUNT(f.id) FILTER (WHERE f.presente) AS presencas,
       COUNT(f.id) FILTER (WHERE NOT f.presente) AS faltas,
       CASE WHEN COUNT(f.id) = 0 THEN 0
            ELSE ROUND(100.0 * COUNT(f.id) FILTER (WHERE f.presente) / COUNT(f.id), 2)
       END AS percentual_frequencia
FROM app.matriculas m
JOIN app.alunos a ON a.id = m.aluno_id
JOIN app.turmas t ON t.id = m.turma_id
LEFT JOIN app.frequencias f ON f.matricula_id = m.id
GROUP BY m.id, a.nome, t.nome;

