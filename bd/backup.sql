CREATE TABLE app.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    nome VARCHAR(120) NOT NULL,
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('PROFESSOR', 'COORDENADOR')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE app.alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    matricula VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE app.disciplinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    carga_horaria INT NOT NULL CHECK (carga_horaria > 0)
);
CREATE TABLE app.turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    disciplina_id BIGINT NOT NULL REFERENCES app.disciplinas(id) ON DELETE RESTRICT,
    professor_id BIGINT NOT NULL REFERENCES app.usuarios(id) ON DELETE RESTRICT,
    periodo VARCHAR(20) NOT NULL
);
CREATE TABLE app.matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id BIGINT NOT NULL REFERENCES app.turmas(id) ON DELETE CASCADE,
    aluno_id BIGINT NOT NULL REFERENCES app.alunos(id) ON DELETE CASCADE,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (turma_id, aluno_id)
);
CREATE TABLE app.notas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL UNIQUE REFERENCES app.matriculas(id) ON DELETE CASCADE,
    nota1 NUMERIC(4,2) NOT NULL CHECK (nota1 BETWEEN 0 AND 10),
    nota2 NUMERIC(4,2) NOT NULL CHECK (nota2 BETWEEN 0 AND 10),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE app.frequencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL REFERENCES app.matriculas(id) ON DELETE CASCADE,
    data_aula DATE NOT NULL,
    presente BOOLEAN NOT NULL,
    UNIQUE (matricula_id, data_aula)
);
CREATE TABLE audit.log_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabela VARCHAR(100) NOT NULL,
    operacao VARCHAR(15) NOT NULL,
    registro_id BIGINT,
    usuario_id BIGINT,
    role_db TEXT NOT NULL,
    dados_antes JSONB,
    dados_depois JSONB,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
